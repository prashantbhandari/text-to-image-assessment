    href: {
        type: String,
        required: true,
    },
    active: {
        type: Boolean,
    },
});

const classes = computed(() =>
    props.active
        ? 'block w-full ps-3 pe-4 py-2 border-l-4 border-accent text-start text-base font-medium text-brand bg-brand/10 focus:outline-none focus:text-brand focus:bg-accent/10 focus:border-accent transition duration-150 ease-in-out'
        : 'block w-full ps-3 pe-4 py-2 border-l-4 border-transparent text-start text-base font-medium text-muted hover:text-fg hover:bg-surface-2 hover:border-muted focus:outline-none focus:text-fg focus:bg-surface-2 focus:border-muted transition duration-150 ease-in-out',
);
</script>

<template>
    <Link :href="href" :class="classes">
        <slot />
    </Link>
</template>
